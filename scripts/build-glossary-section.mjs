// Regenerate the user guide's Statistics glossary section from the
// engine's own _GB_GLOSSARY data, so the guide and the in-app glossary
// can never drift. Run after any glossary edit in graphbuilder2.js:
//
//   node scripts/build-glossary-section.mjs
//
// Idempotent: replaces the marked region in docs/user-guide.html, or
// inserts it before the Keyboard reference section on first run.
// Background (Aug 2026): jamovi asked for the glossary to live in the
// online user guide rather than the results column; in jamovi the "?"
// panel links here, while the standalone keeps its in-panel glossary.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const enginePath = path.join(root, 'inst', 'widget', 'graphbuilder2.js');
const guidePath = path.join(root, 'docs', 'user-guide.html');

const src = readFileSync(enginePath, 'utf8');

function extract(name) {
    const declAt = src.indexOf(`var ${name} = [`);
    if (declAt < 0) throw new Error(`${name} not found in the engine`);
    // terminator: the first line after the declaration that is exactly
    // indentation + "];" (entry prose never sits alone on a line)
    const endMatch = /\n\s*\];/g;
    endMatch.lastIndex = declAt;
    const m = endMatch.exec(src);
    if (!m) throw new Error(`${name} terminator not found`);
    const code = src.slice(declAt, m.index + m[0].length);
    const sandbox = {};
    vm.createContext(sandbox);
    vm.runInContext(code, sandbox);
    return sandbox[name];
}

const GROUPS = extract('_GB_GLOSS_GROUPS');
const TERMS = extract('_GB_GLOSSARY');
if (!Array.isArray(GROUPS) || !Array.isArray(TERMS) || TERMS.length < 50) {
    throw new Error(`extraction looks wrong: ${GROUPS && GROUPS.length} groups, ${TERMS && TERMS.length} terms`);
}

const esc = (s) => String(s || '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

let out = [];
out.push('<!-- GB2-GLOSSARY-START (generated by scripts/build-glossary-section.mjs - edit the data in graphbuilder2.js, not this section) -->');
out.push('<!-- ============================================================ -->');
out.push('<h2 id="glossary">Statistics glossary</h2>');
out.push('<p>Every statistical term Pandion Plots prints, in plain language. Each entry says what the number is, how to read it, and the misreading to avoid. The same definitions back the tap-a-term popovers in the Σ Statistics panel, and this section is generated from that single source, so the two always agree. In the standalone app the glossary also lives inside the chart’s "?" panel; in jamovi it lives here.</p>');
for (let g = 0; g < GROUPS.length; g++) {
    const entries = TERMS.filter((t) => t.g === g);
    if (!entries.length) continue;
    out.push(`<h3 id="glossary-${slug(GROUPS[g])}">${esc(GROUPS[g])}</h3>`);
    for (const t of entries) {
        const sym = t.y && t.y !== t.n ? ` <span style="color:#666;font-weight:400">(${esc(t.y)})</span>` : '';
        const mods = Array.isArray(t.m) && t.m.length
            ? `<span style="color:#666;font-size:.85em"> · ${esc(t.m.join(', '))}</span>` : '';
        out.push('<div class="glossentry" style="margin:0 0 14px">');
        out.push(`<p style="margin:10px 0 2px"><b>${esc(t.n)}</b>${sym}${mods}</p>`);
        out.push(`<p style="margin:2px 0">${esc(t.b)}</p>`);
        if (t.r) out.push(`<p style="margin:2px 0"><b>How to read it.</b> ${esc(t.r)}</p>`);
        if (t.w) out.push(`<p style="margin:2px 0"><b>Common misread.</b> ${esc(t.w)}</p>`);
        out.push('</div>');
    }
}
out.push('<!-- GB2-GLOSSARY-END -->');
const section = out.join('\n');

let guide = readFileSync(guidePath, 'utf8');
const startMark = '<!-- GB2-GLOSSARY-START';
const endMark = '<!-- GB2-GLOSSARY-END -->';
const s = guide.indexOf(startMark);
if (s >= 0) {
    const e = guide.indexOf(endMark, s);
    if (e < 0) throw new Error('start marker without end marker');
    guide = guide.slice(0, s) + section + guide.slice(e + endMark.length);
    console.log('glossary section REPLACED in place');
} else {
    const anchor = '<h2 id="keyboard">';
    const a = guide.indexOf(anchor);
    if (a < 0) throw new Error('keyboard anchor not found');
    // insert before the separator comment that precedes the keyboard h2
    const sepAt = guide.lastIndexOf('<!-- =', a);
    const at = sepAt > 0 ? sepAt : a;
    guide = guide.slice(0, at) + section + '\n\n' + guide.slice(at);
    console.log('glossary section INSERTED before the keyboard reference');
}
writeFileSync(guidePath, guide);
console.log(`groups: ${GROUPS.length}, terms: ${TERMS.length}, guide now ${guide.length} bytes`);
