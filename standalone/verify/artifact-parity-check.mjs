// Release gate: generated public artifacts must describe the exact source
// state being tested. This check does not rebuild or silently repair them.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

function ok(cond, msg) {
    if (!cond) throw new Error(msg);
    console.log('  ok  ' + msg);
}
const root = path.resolve(new URL('.', import.meta.url).pathname, '..', '..');
const read = rel => fs.readFileSync(path.join(root, rel));
const text = rel => read(rel).toString('utf8');
const dist = read('standalone/dist/pandion-plots.html');
const portable = read('website/pandion-plots.html');

ok(Buffer.compare(dist, portable) === 0,
   'website portable download is byte-identical to standalone dist');

const sourceHtml = text('standalone/index.html');
const appHtml = text('website/app/index.html');
const srcs = [...sourceHtml.matchAll(/<script src="([^"]+\.js)"><\/script>/g)]
    .map(m => m[1]);
ok(srcs.length > 0, `standalone declares ${srcs.length} script assets`);
const expected = new Set();
for (const src of srcs) {
    const sourcePath = path.resolve(root, 'standalone', src);
    const data = fs.readFileSync(sourcePath);
    const digest = crypto.createHash('md5').update(data).digest('hex').slice(0, 10);
    const base = path.basename(sourcePath, '.js');
    const hashed = `${base}.${digest}.js`;
    expected.add(hashed);
    ok(appHtml.includes(`src="lib/${hashed}"`),
       `hosted shell references current ${base} hash`);
    ok(Buffer.compare(data, read(`website/app/lib/${hashed}`)) === 0,
       `hosted ${base} bytes match source`);
    const inline = data.toString('utf8').replaceAll('</script', '<\\/script');
    ok(dist.toString('utf8').includes(`<script>\n${inline}\n</script>`),
       `portable dist contains current ${base} bytes`);
}
const actual = new Set(fs.readdirSync(path.join(root, 'website/app/lib'))
    .filter(name => name.endsWith('.js')));
ok(actual.size === expected.size &&
   [...actual].every(name => expected.has(name)),
   'hosted app contains no stale hashed JavaScript assets');
ok(/GENERATED by standalone\/build-dist\.sh/.test(dist.toString('utf8')),
   'portable dist carries its generated-file marker');
ok(/GENERATED by website\/build\.sh/.test(appHtml),
   'hosted app shell carries its generated-file marker');
console.log('ARTIFACT PARITY CHECK PASS');
